"""Coordinator check from physical point triples; imports no search code."""
import hashlib
import itertools
import json
from collections import Counter
from pathlib import Path

HERE = Path(__file__).resolve().parent


def check():
    path = HERE / 'upper' / 'witnesses.json'
    w = json.loads(path.read_text(encoding='utf-8'))['witnesses'][0]
    marks, block = w['A'], set(w['Q'])
    cells = [(v, u) for v in marks for u in marks if u < v]
    if cells != [tuple(p) for p in w['cells']]:
        raise ValueError('Incomplete or unordered physical source')
    # Sorting by first and then second coordinate makes the three points a,b,c.
    triples = []
    for raw in itertools.combinations(cells, 3):
        a, b, c = sorted(raw)
        if a[1] == b[1] and b[0] == c[0] and b[0]-a[0] == c[1]-b[1] > 0:
            triples.append((a, b, c))
    multiplicity = Counter(x-y for x, y in cells)
    parity_bound = sum(n % 2 for n in multiplicity.values())
    outputs = []
    for name in ('before', 'after'):
        values = w[name]
        if len(values) != len(cells) or any(type(c) is not int or c not in (0, 1) for c in values):
            raise ValueError('Invalid full coloring')
        color = dict(zip(cells, values))
        mono = [t for t in triples if len({color[p] for p in t}) == 1]
        if mono:
            raise ValueError(('Monochromatic L', mono[0]))
        all_s, block_s = Counter(), Counter()
        for (x, y), c in color.items():
            all_s[x-y] += 1-2*c
            if x in block and y in block:
                block_s[x-y] += 1-2*c
        outputs.append({'state': name, 'phi_A': sum(v*v for v in all_s.values()),
                        'phi_Q': sum(v*v for v in block_s.values()),
                        's_A': dict(sorted(all_s.items())), 's_Q': dict(sorted(block_s.items()))})
    changed = [p for p, a, b in zip(cells, w['before'], w['after']) if a != b]
    if changed != [(6, 5)]:
        raise ValueError('Unexpected changed boundary')
    result = {'status': 'PASS', 'physical_cells': len(cells), 'corners': len(triples),
              'changed': changed, 'global_parity_lower_bound': parity_bound,
              'states': outputs,
              'before_attains_absolute_global_minimum': outputs[0]['phi_A'] == parity_bound,
              'input_sha256': hashlib.sha256(path.read_bytes()).hexdigest(),
              'checker_sha256': hashlib.sha256(Path(__file__).read_bytes()).hexdigest(),
              'scope': 'Two explicit states; geometric triples generated by all unordered triples. '
                       'Parity lower bound applies to all sign assignments on this source, even improper ones. '
                       'No other-boundary enumeration or minimal-source claim.'}
    out = HERE / 'upper_witness_audit.json'
    out.write_text(json.dumps(result, indent=2)+'\n', encoding='utf-8')
    print(json.dumps(result, indent=2))


if __name__ == '__main__':
    check()
